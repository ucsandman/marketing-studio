// Overlay Content Brief copy when a valid brief exists. Structural checks below
// mirror studio/src/lib/brief.ts (the canonical zod schema, used by the studio +
// tests) — same convention the build-*-audio scripts use to mirror launchTiming.
// A missing or malformed brief falls through to the hardcoded copy untouched, so
// output is byte-identical with no brief present.
const briefPath = join(root, 'out', brand, 'marketing', 'brief.json');
if (existsSync(briefPath)) {
  const brief = validBrief(readFileSync(briefPath, 'utf8'));
  if (!brief) {
    console.warn(`build-launch-props: out/${brand}/marketing/brief.json is invalid; using hardcoded copy`);
  } else {
    if (brief.hook.headline) launch.headline = brief.hook.headline;
    if (brief.cta) launch.cta = brief.cta;
    // Overlay copy by feature index; screenshots/structure stay local. A feature may
    // name the brief entry it carries with `briefIndex` when the film's act order
    // differs from the brief's; without one the index is the identity mapping, so
    // every existing brand overlays exactly as before.
    launch.features.forEach((f, i) => {
      const bf = brief.features[f.briefIndex ?? i];
      if (!bf) return;
      if (bf.heading) f.heading = bf.heading;
      if (bf.benefitLines.length) f.lines = bf.benefitLines.slice(0, 3);
    });
  }
}
// briefIndex is authoring metadata for this script, not a LaunchVideo prop.
launch.features.forEach((f) => delete f.briefIndex);

// VO-derived picture locks embed the audio manifest (see EMBED_AUDIO above).
